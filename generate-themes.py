#!/usr/bin/env python3
"""Generate fixed light/dark pages from the default light HTML sources."""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent
PAGES = (
    Path("index.html"),
    Path("privacy/index.html"),
    Path("terms/index.html"),
    Path("delete-account/index.html"),
    Path("rusttrados/index.html"),
)
PAGE_URLS = {"/" + str(page).removesuffix("index.html") for page in PAGES}


def themed_page(source: str, theme: str, voice: str = "george") -> str:
    page = re.sub(r'\s*<script src="/theme.min.js"></script>', "", source)
    page = page.replace('data-theme="light"', f'data-theme="{theme}"', 1)
    page = page.replace('content="light"', f'content="{theme}"', 1)

    # The alternative sample is inert in the source page. Generated homepages
    # contain just the selected video, so navigation stops the previous audio.
    alternative = re.search(r'\s*<template id="tts-alba-template">(.*?)</template>', page, re.S)
    if alternative:
        page = page.replace(alternative[0], "")
        if voice == "alba":
            page = re.sub(
                r'<figure id="listen"[^>]*>.*?</figure>',
                lambda _: alternative[1].strip(), page, count=1, flags=re.S,
            )

        links = []
        for name in ("george", "alba"):
            route = f'/{theme}/' + ("alba/" if name == "alba" else "") + "#listen"
            current = ' aria-current="page"' if name == voice else ""
            links.append(f'        <a href="{route}"{current}>{name.title()}</a>')
        control = '<nav class="narration-voices" aria-label="Reading voice">\n' + "\n".join(links) + '\n      </nav>'
        page = re.sub(r'<nav class="narration-voices"[^>]*>.*?</nav>', lambda _: control, page, count=1, flags=re.S)

    # Ordinary links retain the theme while navigating between site pages.
    def page_link(match: re.Match) -> str:
        path = match[1]
        return f'href="/{theme}{path}"' if path in PAGE_URLS else match[0]

    page = re.sub(r'href="(/[^"]*)"', page_link, page)
    if theme == "dark":
        page = page.replace(' aria-current="page"', "", 1)
        page = re.sub(r'(<a href="/dark/[^"]*")>Dark</a>', r'\1 aria-current="page">Dark</a>', page, count=1)
        page = page.replace('src="/icon/bokheim.svg"', 'src="/screenshots/dark/bokheim.svg?v=2"')
        page = page.replace('href="/icon/bokheim.svg"', 'href="/screenshots/dark/bokheim.svg?v=2"')
        page = re.sub(
            r'\b(src|poster|href)="/screenshots/([^"/]+\.(?:webp|gif|mp4))"',
            r'\1="/screenshots/dark/\2"',
            page,
        )
    if alternative and voice == "alba":
        def theme_links(match: re.Match) -> str:
            return match[0].replace('href="/light/"', 'href="/light/alba/#listen"').replace('href="/dark/"', 'href="/dark/alba/#listen"')

        page = re.sub(r'<nav class="theme-control"[^>]*>.*?</nav>', theme_links, page, count=1, flags=re.S)
    return "<!-- Generated by generate-themes.py; edit the corresponding default page. -->\n" + page


if __name__ == "__main__":
    count = 0
    for source_path in PAGES:
        source = (ROOT / source_path).read_text()
        for theme in ("light", "dark"):
            target = ROOT / theme / source_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(themed_page(source, theme))
            count += 1
            if source_path == Path("index.html"):
                target = ROOT / theme / "alba/index.html"
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(themed_page(source, theme, voice="alba"))
                count += 1
    print(f"Generated {count} static theme pages.")
